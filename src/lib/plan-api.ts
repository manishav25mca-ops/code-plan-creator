// Client-side API helper: streams the plan text from the server.
export interface ProjectDetails {
  title: string;
  description: string;
  projectType: string;
  techStack: string;
  teamSize: string;
  duration: string;
  experience: string;
}

const ERROR_MARKER = "\u0000ERROR:";

export async function streamPlan(
  details: ProjectDetails,
  onText: (full: string) => void,
  signal: AbortSignal,
): Promise<string> {
  const payload: Record<string, unknown> = { title: details.title };
  if (details.description) payload["description"] = details.description;
  if (details.projectType) payload["projectType"] = details.projectType;
  if (details.techStack) payload["techStack"] = details.techStack;
  if (details.teamSize) payload["teamSize"] = Number(details.teamSize);
  if (details.duration) payload["duration"] = details.duration;
  if (details.experience) payload["experience"] = details.experience;

  let res: Response;
  try {
    res = await fetch("/api/generate-plan", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(payload),
      signal,
    });
  } catch {
    throw new Error("Could not reach the server. Check your connection and try again.");
  }
  if (!res.ok || !res.body) {
    const data = await res.json().catch(() => null);
    throw new Error(data?.error ?? "The plan could not be generated. Please try again.");
  }

  const reader = res.body.getReader();
  const decoder = new TextDecoder();
  let text = "";
  while (true) {
    const { done, value } = await reader.read();
    if (done) break;
    text += decoder.decode(value, { stream: true });
    const idx = text.indexOf(ERROR_MARKER);
    if (idx !== -1) throw new Error(text.slice(idx + ERROR_MARKER.length));
    onText(text);
  }
  return text;
}

export interface PlanSection {
  title: string;
  body: string;
}

/** Split the Markdown plan into its "## N. Title" sections. */
export function splitSections(md: string): PlanSection[] {
  const parts = md.split(/^##\s+/m).slice(1);
  return parts.map((p) => {
    const nl = p.indexOf("\n");
    return { title: (nl === -1 ? p : p.slice(0, nl)).trim(), body: nl === -1 ? "" : p.slice(nl + 1).trim() };
  });
}

export function planToMarkdown(details: ProjectDetails, md: string) {
  return `# Project Plan: ${details.title}\n\n_Generated by Project Planning Agent. All durations are estimates._\n\n${md}\n`;
}
